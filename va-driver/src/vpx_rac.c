int vpx_rac_init(struct vpx_rac *c, const uint8_t *buf, size_t buf_size)
{
	c->high = 255;
	c->bits = -16;
	c->buffer = buf;
	c->end = buf + buf_size;
	c->end_reached = 0;
	if (buf_size < 3)
		return -1;
	c->code_word = ((unsigned int)buf[0] << 16) |
		       ((unsigned int)buf[1] << 8) | buf[2];
	c->buffer += 3;
	return 0;
}
